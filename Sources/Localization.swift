import Foundation

enum Lang {
    // "auto" = langue de l'iPhone, "fr" ou "en" = choix manuel
    static var isEnglish: Bool {
        let setting = UserDefaults.standard.string(forKey: "lang") ?? "auto"
        if setting == "en" { return true }
        if setting == "fr" { return false }
        return !(Locale.preferredLanguages.first ?? "fr").hasPrefix("fr")
    }

    static var locale: Locale {
        return Locale(identifier: isEnglish ? "en_US" : "fr_CA")
    }
}

func tr(_ fr: String) -> String {
    if !Lang.isEnglish { return fr }
    return englishStrings[fr] ?? fr
}

